-- 17_labor_basis_wording.sql — 工資牌價依據改寫為不綁單一縣市
--
-- 原文寫「臺北市政府工程預算參考單價」。院方在桃園，採購看到台北會問
-- 「為什麼用台北的價」。查證結果：桃園市沒有等同的年度工程預算參考單價
-- （市府價格庫最新訪價停在 110 年 9 月，已五年未更新），因此不改數字，
-- 只把說法改成「直轄市工程預算參考單價」——桃園市本身即直轄市，
-- 敘述涵蓋且不指名——並加註以主計總處 CCI 勞務類指數檢核工資水準。
--
-- 牌價維持 3,000 元/工（375 元/時 × 8 小時）。
-- ═══════════════════════════════════════════════════════════════

update price_items
   set evidence_note =
         '牌價 3,000 元/工，係參照直轄市工程預算參考單價之技術工單價（375 元/時 × 8 小時），'
         '並以行政院主計總處營造工程物價指數（CCI）勞務類指數檢核工資水準；'
         '因本院已訂有物業管理合約，本項按牌價 9 折計價為 2,700 元/工。'
         '法定下限為勞動部基本工資時薪 196 元 × 8 小時 = 1,568 元/工。'
         '夜間、休息日及例假日之加成依勞動基準法第 24、39 條計算'
 where id = 'lb-tech-day';

-- 檢查
select id, name, std_price, evidence_id, evidence_note from price_items where id = 'lb-tech-day';
